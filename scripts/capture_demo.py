from pathlib import Path
from datetime import date, timedelta
from playwright.sync_api import sync_playwright

out = Path('reports/screenshots'); out.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch()
    context = browser.new_context(viewport={'width':1600,'height':900}, record_video_dir='reports/video', record_video_size={'width':1600,'height':900})
    page = context.new_page()
    page.goto('http://localhost:8081/')
    page.get_by_placeholder('Email').wait_for()
    page.screenshot(path=str(out/'01-login.png'))
    page.wait_for_timeout(1500)
    page.get_by_placeholder('Email').fill('fa2-demo@example.com')
    page.get_by_placeholder('Password',exact=True).fill('DemoPass123!')
    page.get_by_role('button',name='Login',exact=True).click()
    page.get_by_text('Welcome, FA2 Demo').wait_for()
    page.get_by_text('Milk',exact=True).wait_for()
    page.wait_for_timeout(1500)
    page.screenshot(path=str(out/'02-dashboard.png'))
    page.get_by_placeholder('Product name').first.fill('FA2 Live Demo Item')
    page.locator('input[type=date]').first.fill((date.today()+timedelta(days=3)).isoformat())
    page.get_by_role('button',name='Add Product',exact=True).click()
    page.get_by_text('FA2 Live Demo Item',exact=True).wait_for()
    page.wait_for_timeout(2000)
    page.screenshot(path=str(out/'03-add-product.png'))
    page.get_by_role('button',name='Edit',exact=True).first.click()
    page.screenshot(path=str(out/'04-edit-product.png'))
    page.wait_for_timeout(1500)
    page.locator('section').nth(1).locator('input').first.fill('FA2 Updated Demo Item')
    page.get_by_role('button',name='Save',exact=True).click()
    page.get_by_text('FA2 Updated Demo Item',exact=True).wait_for()
    page.screenshot(path=str(out/'05-saved-update.png'))
    page.wait_for_timeout(2000)
    page.get_by_role('button',name='Delete',exact=True).first.click()
    page.get_by_text('FA2 Updated Demo Item',exact=True).wait_for(state='hidden')
    page.wait_for_timeout(2000)
    page.screenshot(path=str(out/'06-after-delete.png'))
    context.close()
    browser.close()
